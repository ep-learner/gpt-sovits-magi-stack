# -*- coding: utf-8 -*-
# apply-config：读取 config\stack.yaml（+ stack.local.yaml 覆盖），
#   1) 生成 config\_env.bat / _env.ps1 / _env.py 供脚本消费；
#   2) 把 current_voice 同步到 API 端 tts_infer.yaml 与 MAGI 端 library.json。
# 幂等，可重复运行。用法：直接运行本脚本，或被 switch-voice / 启动器调用。

. (Join-Path $PSScriptRoot 'lib.ps1')
$ErrorActionPreference = 'Stop'

function Escape-Batch([string]$s) {
    if ($null -eq $s) { return '' }
    $s = $s -replace '%', '%%'
    $s = $s -replace '\^', '^^'
    $s = $s -replace '&', '^&'
    $s = $s -replace '\|', '^|'
    $s = $s -replace '<', '^<'
    $s = $s -replace '>', '^>'
    return $s
}
function Escape-PsStr([string]$s) {
    if ($null -eq $s) { return '' }
    return ($s -replace "'", "''")
}

$cfg = Get-StackConfig
$repo = Get-RepoRoot
$p = $cfg['paths']
$cache = $cfg['cache']
$srv = $cfg['server']
$cv = $cfg['current_voice']
$root = $p['gpt_sovits_root']

Write-Host "== apply-config ==" -ForegroundColor Cyan
Write-Host "repo             : $repo"
Write-Host "gpt_sovits_root  : $root"
Write-Host "api              : $($p['api_base'])"
Write-Host "current_voice    : $($cv['exp_name'])"

# ---------- 1. 生成 _env.bat ----------
$bat = @"
@echo off
REM Auto-generated by scripts\apply-config.ps1 - DO NOT EDIT.
REM Source: config\stack.yaml (+ config\stack.local.yaml if present)
set "ROOT=$(Escape-Batch $root)"
set "HOST=$(Escape-Batch $srv['host'])"
set "PORT=$(Escape-Batch $srv['port'])"
set "API_BASE=$(Escape-Batch $p['api_base'])"
set "NUMBA_CACHE_DIR=$(Escape-Batch $cache['numba'])"
set "HF_HOME=$(Escape-Batch $cache['huggingface'])"
set "HF_HUB_CACHE=$(Escape-Batch $cache['huggingface'])"
set "MODELSCOPE_CACHE=$(Escape-Batch $cache['modelscope'])"
set "MAGI_EXE=$(Escape-Batch $p['magi_exe'])"
set "MAGI_LIBRARY_JSON=$(Escape-Batch $p['magi_library_json'])"
set "INPUT_DIR=$(Escape-Batch $p['input_dir'])"
set "VERSION=$(Escape-Batch $cfg['version'])"
set "CFG_EXP_NAME=$(Escape-Batch $cv['exp_name'])"
set "CFG_REF_AUDIO=$(Escape-Batch $cv['ref_audio'])"
set "CFG_PROMPT_TEXT=$(Escape-Batch $cv['prompt_text'])"
set "CFG_TEXT_LANG=$(Escape-Batch $cv['text_lang'])"
set "CFG_PROMPT_LANG=$(Escape-Batch $cv['prompt_lang'])"
"@
$bat = $bat -replace "`r?`n", "`r`n"
Write-Utf8NoBom (Join-Path $repo 'config\_env.bat') $bat

# ---------- 2. 生成 _env.ps1 ----------
function Q([string]$v) { return "'" + (Escape-PsStr $v) + "'" }
$pad = { param($n) (' ' * [Math]::Max(0, (22 - $n))) }
$ps = @"
# Auto-generated by scripts\apply-config.ps1 — DO NOT EDIT.
# Source: config\stack.yaml (+ config\stack.local.yaml if present)
`$cfgRoot             = $(Q $root)
`$cfgHost             = $(Q $srv['host'])
`$cfgPort             = $(Q $srv['port'])
`$cfgApiBase          = $(Q $p['api_base'])
`$cfgNumbaCacheDir    = $(Q $cache['numba'])
`$cfgHfHome           = $(Q $cache['huggingface'])
`$cfgHfHubCache       = $(Q $cache['huggingface'])
`$cfgModelscopeCache  = $(Q $cache['modelscope'])
`$cfgMagiExe          = $(Q $p['magi_exe'])
`$cfgMagiLibraryJson  = $(Q $p['magi_library_json'])
`$cfgInputDir         = $(Q $p['input_dir'])
`$cfgVersion          = $(Q $cfg['version'])
`$cfgExpName          = $(Q $cv['exp_name'])
`$cfgRefAudio         = $(Q $cv['ref_audio'])
`$cfgPromptText       = $(Q $cv['prompt_text'])
`$cfgTextLang         = $(Q $cv['text_lang'])
`$cfgPromptLang       = $(Q $cv['prompt_lang'])
"@
Write-Utf8Bom (Join-Path $repo 'config\_env.ps1') $ps

# ---------- 3. 生成 _env.py ----------
function PyRaw([string]$v) {
    if ($v -match "'") { return "'" + ($v -replace "'", "\'") + "'" }
    return "r'" + $v + "'"
}
function PyStr([string]$v) { return "'" + ($v -replace "'", "\'") + "'" }
$py = @"
# -*- coding: utf-8 -*-
# Auto-generated by scripts\apply-config.ps1 — DO NOT EDIT.
# Source: config\stack.yaml (+ config\stack.local.yaml if present)
GPT_SOVITS_ROOT     = $(PyRaw $root)
HOST                = $(PyStr $srv['host'])
PORT                = $(PyStr $srv['port'])
API_BASE            = $(PyStr $p['api_base'])
NUMBA_CACHE_DIR     = $(PyRaw $cache['numba'])
HF_HOME             = $(PyRaw $cache['huggingface'])
HF_HUB_CACHE        = $(PyRaw $cache['huggingface'])
MODELSCOPE_CACHE    = $(PyRaw $cache['modelscope'])
MAGI_EXE            = $(PyRaw $p['magi_exe'])
MAGI_LIBRARY_JSON   = $(PyRaw $p['magi_library_json'])
INPUT_DIR           = $(PyRaw $p['input_dir'])
VERSION             = $(PyStr $cfg['version'])
CFG_EXP_NAME        = $(PyStr $cv['exp_name'])
CFG_REF_AUDIO       = $(PyRaw $cv['ref_audio'])
CFG_PROMPT_TEXT     = $(PyStr $cv['prompt_text'])
CFG_TEXT_LANG       = $(PyStr $cv['text_lang'])
CFG_PROMPT_LANG     = $(PyStr $cv['prompt_lang'])
"@
Write-Utf8NoBom (Join-Path $repo 'config\_env.py') $py

# ---------- 4. 同步到 tts_infer.yaml 的 custom 段 ----------
# 新电脑尚未训练任何音色时，权重不存在属正常情况：保留 API 默认配置并给出提示，不中断初始化。
$w = $null
try {
    $w = Get-LatestWeights -Root $root -Exp $cv['exp_name']
} catch {
    Write-Warning "当前音色“$($cv['exp_name'])”还没有可用权重：$($_.Exception.Message)"
}
$yamlPath = Join-Path $root 'GPT_SoVITS\configs\tts_infer.yaml'
if (-not $w) {
    Write-Warning "已跳过 tts_infer.yaml 同步。请先用启动器训练一个新音色，再重新应用配置。"
} elseif (Test-Path -LiteralPath $yamlPath) {
    $customBlock = @"
custom:
  bert_base_path: GPT_SoVITS/pretrained_models/chinese-roberta-wwm-ext-large
  cnhuhbert_base_path: GPT_SoVITS/pretrained_models/chinese-hubert-base
  device: cuda
  is_half: true
  t2s_weights_path: $($w['gpt_rel'])
  version: $($cfg['version'])
  vits_weights_path: $($w['sovits_rel'])
"@
    $yaml = [System.IO.File]::ReadAllText($yamlPath)
    $newYaml = [regex]::Replace($yaml, '(?ms)^custom:\r?\n(?:[ \t]+.*\r?\n)*', $customBlock + "`r`n")
    Write-Utf8NoBom $yamlPath $newYaml
    Write-Host "tts_infer.yaml   : custom -> $($cv['exp_name']) ($($w['gpt_rel']) / $($w['sovits_rel']))"
} else {
    Write-Warning "找不到 tts_infer.yaml: $yamlPath"
}

# ---------- 5. 同步到 MAGI library.json 的 settings.tts ----------
$libPath = $p['magi_library_json']
if (Test-Path -LiteralPath $libPath) {
    $bak = "$libPath.bak"
    if (-not (Test-Path -LiteralPath $bak)) { Copy-Item -LiteralPath $libPath -Destination $bak -Force }
    $obj = Get-Content -LiteralPath $libPath -Raw -Encoding UTF8 | ConvertFrom-Json
    if (-not $obj.settings) { $obj | Add-Member -NotePropertyName settings -NotePropertyValue ([pscustomobject]@{}) -Force }
    if (-not $obj.settings.tts) { $obj.settings | Add-Member -NotePropertyName tts -NotePropertyValue ([pscustomobject]@{}) -Force }
    $tts = $obj.settings.tts
    $tts | Add-Member -NotePropertyName baseUrl -NotePropertyValue $p['api_base'] -Force
    $tts | Add-Member -NotePropertyName refAudioPath -NotePropertyValue $cv['ref_audio'] -Force
    $tts | Add-Member -NotePropertyName promptText -NotePropertyValue $cv['prompt_text'] -Force
    $tts | Add-Member -NotePropertyName textLang -NotePropertyValue $cv['text_lang'] -Force
    $tts | Add-Member -NotePropertyName promptLang -NotePropertyValue $cv['prompt_lang'] -Force
    $apiVersion = if ($cfg.Contains('magi') -and $cfg['magi']['api_version']) { $cfg['magi']['api_version'] } else { 'v2' }
    $tts | Add-Member -NotePropertyName apiVersion -NotePropertyValue $apiVersion -Force
    $json = $obj | ConvertTo-Json -Depth 100 -Compress
    Write-Utf8NoBom $libPath $json
    Write-Host "library.json     : tts -> ref=$($cv['ref_audio'])"
} else {
    Write-Warning "找不到 library.json: $libPath（MAGI 未运行过？）"
}

Write-Host "== 完成 ==" -ForegroundColor Green
